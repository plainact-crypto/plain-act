import { readFile, writeFile } from "node:fs/promises";

const mainPath=new URL("../src/main.js",import.meta.url);
const patchPath=new URL("../training-lines-patch.js",import.meta.url);
const strictPath=new URL("../guided-strict-best-final.js",import.meta.url);
const depthProgressionPath=new URL("../variation-depth-progression-patch.js",import.meta.url);
const rankLadderPath=new URL("../rank-ladder-patch.js",import.meta.url);
const gameEndFixPath=new URL("../game-end-continuation-fix.js",import.meta.url);
const continuationGuardPath=new URL("../exact-continuation-prefix-guard.js",import.meta.url);
const gameEndRankUnlockPath=new URL("../game-end-rank-unlock-patch.js",import.meta.url);
let main=await readFile(mainPath,"utf8");
const patch=await readFile(patchPath,"utf8");
const strict=await readFile(strictPath,"utf8");
const depthProgression=await readFile(depthProgressionPath,"utf8");
const rankLadder=await readFile(rankLadderPath,"utf8");
const gameEndFix=await readFile(gameEndFixPath,"utf8");
const continuationGuard=await readFile(continuationGuardPath,"utf8");
const gameEndRankUnlock=await readFile(gameEndRankUnlockPath,"utf8");
if(!main.includes("__COT_INDEPENDENT_TRAINING_LINES__")) main+=`\n${patch}\n`;
if(!main.includes("__COT_GUIDED_STRICT_BEST_FINAL__")) main+=`\n${strict}\n`;
if(!main.includes("__COT_VARIATION_DEPTH_PROGRESSION__")) main+=`\n${depthProgression}\n`;
if(!main.includes("__COT_ONE_GAME_RANK_LADDER__")) main+=`\n${rankLadder}\n`;
if(!main.includes("__COT_GAME_END_CONTINUATION_FIX__")) main+=`\n${gameEndFix}\n`;
if(!main.includes("__COT_EXACT_CONTINUATION_PREFIX_GUARD__")) main+=`\n${continuationGuard}\n`;
if(!main.includes("__COT_GAME_END_RANK_UNLOCK__")) main+=`\n${gameEndRankUnlock}\n`;
await writeFile(mainPath,main);